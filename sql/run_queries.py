"""
Task 2 - Run every query in sql/02_queries.sql and save the results.

Output: sql/query_results.md  (each query + its result table, ready for the report)

Usage (from the repository root, after load_mysql.py):
    python sql/run_queries.py
"""
import re
from datetime import datetime
from decimal import Decimal
from pathlib import Path

from load_mysql import get_connection      # same connection settings as the loader

HERE = Path(__file__).resolve().parent
QUERY_FILE = HERE / "02_queries.sql"
RESULT_FILE = HERE / "query_results.md"


def split_queries(sql_text):
    """Return [(title, sql), ...] using the '-- @query' markers in the file."""
    parts = re.split(r"^-- @query\s+", sql_text, flags=re.MULTILINE)[1:]
    queries = []
    for part in parts:
        title, _, body = part.partition("\n")
        queries.append((title.strip(), body.strip().rstrip(";")))
    return queries


def fmt(value):
    if value is None:
        return "NULL"
    if isinstance(value, datetime):
        return value.strftime("%Y-%m-%d %H:%M:%S")
    if isinstance(value, Decimal):
        return format(value.normalize(), "f")
    return str(value)


def to_markdown(columns, rows):
    lines = ["| " + " | ".join(columns) + " |", "|" + "---|" * len(columns)]
    lines += ["| " + " | ".join(fmt(v) for v in row) + " |" for row in rows]
    return "\n".join(lines)


def main():
    queries = split_queries(QUERY_FILE.read_text(encoding="utf-8"))
    out = ["# MySQL query results (Task 2)", "",
           f"Generated by `sql/run_queries.py` on {datetime.now():%Y-%m-%d %H:%M}.", ""]

    conn = get_connection()
    try:
        with conn.cursor() as cur:
            for title, sql in queries:
                cur.execute(sql)
                columns = [d[0] for d in cur.description]
                rows = cur.fetchall()
                print(f"{title}  ->  {len(rows)} row(s)")
                out += [f"## {title}", "", "```sql", sql, "```", "",
                        f"**Result ({len(rows)} rows):**", "", to_markdown(columns, rows), ""]
    finally:
        conn.close()

    RESULT_FILE.write_text("\n".join(out), encoding="utf-8")
    print(f"Saved results to {RESULT_FILE.relative_to(HERE.parent)}")


if __name__ == "__main__":
    main()
